"""Configuration loading helpers."""

from __future__ import annotations

import tomllib
from collections.abc import Mapping
from typing import TYPE_CHECKING, Literal, cast

from py_init_tools.models import InitToolConfig

if TYPE_CHECKING:
    from pathlib import Path


DiscoveryMode = Literal["explicit_all", "classes_functions", "all_public"]

DEFAULT_GENERATED_MARKER = "Generated by py-init-tools"
DEFAULT_PACKAGE_DESCRIPTION = "Python package."
DEFAULT_DISCOVERY_MODE: DiscoveryMode = "classes_functions"

CONFIG_TABLE_NAME = "py-init-tools"

DEFAULT_IGNORED_DIR_NAMES = frozenset(
    {
        "__pycache__",
        ".git",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        ".pixi",
        "build",
        "dist",
    }
)


def _as_str(value: object, *, default: str) -> str:
    """Return a string config value."""
    if isinstance(value, str):
        return value

    return default


def _as_optional_str(value: object) -> str | None:
    """Return an optional string config value."""
    if value is None:
        return None

    if isinstance(value, str):
        return value

    return None


def _as_bool(value: object, *, default: bool) -> bool:
    """Return a boolean config value."""
    if isinstance(value, bool):
        return value

    return default


def _as_str_list(value: object, *, default: tuple[str, ...] = ()) -> tuple[str, ...]:
    """Return a tuple of strings from a config value."""
    if not isinstance(value, list):
        return default

    items = cast("list[object]", value)

    return tuple(item for item in items if isinstance(item, str))


def _as_discovery_mode(value: object) -> DiscoveryMode:
    """Return a valid discovery mode."""
    valid_modes: frozenset[DiscoveryMode] = frozenset(
        {"explicit_all", "classes_functions", "all_public"}
    )

    if value in valid_modes:
        return value

    return DEFAULT_DISCOVERY_MODE


def _as_str_set(value: object) -> frozenset[str]:
    """Return a frozenset of strings from a config value."""
    return frozenset(_as_str_list(value))


def _as_str_map(value: object) -> dict[str, frozenset[str]]:
    """Return a dictionary mapping strings to string frozensets."""
    if not isinstance(value, Mapping):
        return {}

    mapping = cast("Mapping[object, object]", value)
    result: dict[str, frozenset[str]] = {}

    for key, raw_items in mapping.items():
        if not isinstance(key, str):
            continue

        result[key] = _as_str_set(raw_items)

    return result


def _load_pyproject_data(pyproject_path: Path) -> dict[str, object]:
    """Load raw pyproject.toml data."""
    if not pyproject_path.exists():
        return {}

    with pyproject_path.open("rb") as file:
        data = tomllib.load(file)

    return cast("dict[str, object]", data)


def _get_tool_table(data: Mapping[str, object]) -> dict[str, object]:
    """Return the [tool.py-init-tools] table from pyproject data."""
    tool_table = data.get("tool")

    if not isinstance(tool_table, Mapping):
        return {}

    tool_mapping = cast("Mapping[object, object]", tool_table)
    raw_config = tool_mapping.get(CONFIG_TABLE_NAME)

    if not isinstance(raw_config, Mapping):
        return {}

    return dict(cast("Mapping[str, object]", raw_config))


def _resolve_paths(cwd: Path, paths: tuple[str, ...]) -> tuple[Path, ...]:
    """Resolve string paths relative to the current working directory."""
    return tuple((cwd / path).resolve() for path in paths)


def _configured_paths(
    *,
    cwd: Path,
    cli_paths: tuple[str, ...],
    config_paths: tuple[str, ...],
    default_paths: tuple[str, ...],
) -> tuple[Path, ...]:
    """Resolve CLI paths, then config paths, then defaults."""
    if cli_paths:
        return _resolve_paths(cwd, cli_paths)

    if config_paths:
        return _resolve_paths(cwd, config_paths)

    return _resolve_paths(cwd, default_paths)


def _ignored_dir_names(raw_config: Mapping[str, object]) -> frozenset[str]:
    """Return configured ignored directory names or defaults."""
    configured_names = _as_str_set(raw_config.get("ignored_dir_names"))

    if configured_names:
        return configured_names

    return DEFAULT_IGNORED_DIR_NAMES


def load_config(
    *,
    cwd: Path,
    package_roots: tuple[str, ...],
    test_roots: tuple[str, ...],
) -> InitToolConfig:
    """Load py-init-tools configuration from pyproject.toml and CLI overrides."""
    project_root = cwd.resolve()
    pyproject_path = project_root / "pyproject.toml"

    pyproject_data = _load_pyproject_data(pyproject_path)
    raw_config = _get_tool_table(pyproject_data)

    configured_package_roots = _as_str_list(
        raw_config.get("package_roots"),
        default=("src/py_init_tools",),
    )
    configured_test_roots = _as_str_list(
        raw_config.get("test_roots"),
        default=("tests",),
    )

    resolved_package_roots = _configured_paths(
        cwd=project_root,
        cli_paths=package_roots,
        config_paths=configured_package_roots,
        default_paths=("src/py_init_tools",),
    )
    resolved_test_roots = _configured_paths(
        cwd=project_root,
        cli_paths=test_roots,
        config_paths=configured_test_roots,
        default_paths=("tests",),
    )

    return InitToolConfig(
        project_root=project_root,
        package_roots=resolved_package_roots,
        test_roots=resolved_test_roots,
        generated_marker=_as_str(
            raw_config.get("generated_marker"),
            default=DEFAULT_GENERATED_MARKER,
        ),
        package_version=_as_optional_str(raw_config.get("package_version")),
        package_description=_as_str(
            raw_config.get("package_description"),
            default=DEFAULT_PACKAGE_DESCRIPTION,
        ),
        generate_root_reexports=_as_bool(
            raw_config.get("generate_root_reexports"),
            default=False,
        ),
        reexport_allowlist=_as_str_set(raw_config.get("reexport_allowlist")),
        flat_subdirs=_as_str_set(raw_config.get("flat_subdirs")),
        discovery_mode=_as_discovery_mode(raw_config.get("discovery_mode")),
        export_constants=_as_bool(
            raw_config.get("export_constants"),
            default=False,
        ),
        export_type_aliases=_as_bool(
            raw_config.get("export_type_aliases"),
            default=False,
        ),
        ignored_dir_names=_ignored_dir_names(raw_config),
        private_names_by_module=_as_str_map(
            raw_config.get("private_names_by_module"),
        ),
        private_names_by_dir=_as_str_map(
            raw_config.get("private_names_by_dir"),
        ),
    )
