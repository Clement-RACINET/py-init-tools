def test_root_does_not_reexport_non_allowlisted_subpackage_symbols(
    tmp_path: Path,
) -> None:
    """Do not re-export symbols from a non-allowlisted subpackage at root level."""
    pkg = tmp_path / "demo"
    ui = pkg / "ui"

    write_module(
        ui / "app.py",
        """
def run_ui() -> int:
    return 0
""",
    )

    cfg = InitToolConfig(
        project_root=tmp_path,
        package_roots=(pkg,),
        package_version="1.0.0",
        package_description="Demo package.",
        generate_root_reexports=True,
        reexport_allowlist=frozenset({"core"}),
        discovery_mode="all_public",
    )

    generated = generate_package_files_for_root(cfg, pkg)

    root_init = next(item for item in generated if item.path == pkg / "__init__.py")
    ui_init = next(item for item in generated if item.path == ui / "__init__.py")

    assert "from .ui import run_ui" not in root_init.content
    assert "from .app import run_ui" not in ui_init.content
    assert "# No eager public re-exports" in ui_init.content


