def test_generate_package_files_for_root_generates_deepest_first(
    tmp_path: Path,
) -> None:
    """Generate package files for all package-like directories."""
    cfg = make_config(
        tmp_path,
        generate_root_reexports=True,
        reexport_allowlist=["subpkg", "subpkg/nested"],
    )
    pkg_root = tmp_path / "src" / "example_pkg"

    write_module(pkg_root / "module.py", "class RootClass:\n    pass\n")
    write_module(pkg_root / "subpkg" / "module.py", "class SubClass:\n    pass\n")
    write_module(
        pkg_root / "subpkg" / "nested" / "module.py",
        "class NestedClass:\n    pass\n",
    )

    generated = generate_package_files_for_root(cfg, pkg_root)

    assert [file.path for file in generated] == [
        pkg_root / "subpkg" / "nested" / "__init__.py",
        pkg_root / "subpkg" / "__init__.py",
        pkg_root / "__init__.py",
    ]


