def make_config(  # noqa: PLR0913
    tmp_path: Path,
    *,
    package_roots: list[str] | None = None,
    test_roots: list[str] | None = None,
    package_version: str | None = None,
    package_description: str = "Example package.",
    generated_marker: str = "Generated by test",
    generate_root_reexports: bool = False,
    reexport_allowlist: list[str] | None = None,
    flat_subdirs: list[str] | None = None,
    discovery_mode: str = "classes_functions",
    export_constants: bool = False,
    export_type_aliases: bool = False,
) -> InitToolConfig:
    """Create a test configuration through pyproject.toml loading."""
    pyproject = tmp_path / "pyproject.toml"

    configured_package_roots = package_roots or ["src/example_pkg"]
    configured_test_roots = test_roots or ["tests"]

    package_root_values = ", ".join(f'"{value}"' for value in configured_package_roots)
    test_root_values = ", ".join(f'"{value}"' for value in configured_test_roots)

    lines = [
        "[tool.py-init-tools]",
        f"package_roots = [{package_root_values}]",
        f"test_roots = [{test_root_values}]",
        f'package_description = "{package_description}"',
        f'generated_marker = "{generated_marker}"',
        f"generate_root_reexports = {str(generate_root_reexports).lower()}",
        f'discovery_mode = "{discovery_mode}"',
        f"export_constants = {str(export_constants).lower()}",
        f"export_type_aliases = {str(export_type_aliases).lower()}",
    ]

    if package_version is not None:
        lines.append(f'package_version = "{package_version}"')

    if reexport_allowlist is not None:
        quoted_values = ", ".join(f'"{value}"' for value in reexport_allowlist)
        lines.append(f"reexport_allowlist = [{quoted_values}]")

    if flat_subdirs is not None:
        quoted_values = ", ".join(f'"{value}"' for value in flat_subdirs)
        lines.append(f"flat_subdirs = [{quoted_values}]")

    pyproject.write_text("\n".join(lines), encoding="utf-8")

    return load_config(
        cwd=tmp_path,
        package_roots=(),
        test_roots=(),
    )


def write_module(path: Path, content: str) -> Path:
    """Write a Python module for generator tests."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


def test_dedupe_import_entries_removes_duplicate_public_names() -> None:
    """Remove duplicate public names across import entries."""
    entries = [
        (".a", ["Alpha", "Shared"]),
        (".b", ["Beta", "Shared"]),
        (".c", ["Alpha", "Gamma"]),
    ]

    assert dedupe_import_entries(entries) == [
        (".a", ["Alpha", "Shared"]),
        (".b", ["Beta"]),
        (".c", ["Gamma"]),
    ]


