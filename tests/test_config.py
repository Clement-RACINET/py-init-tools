"""Tests for configuration loading."""

from __future__ import annotations

from typing import TYPE_CHECKING

from py_init_tools.config import load_config

if TYPE_CHECKING:
    from pathlib import Path


def test_load_config_uses_defaults_without_pyproject(tmp_path: Path) -> None:
    """Load default configuration when pyproject.toml is missing."""
    cfg = load_config(
        cwd=tmp_path,
        package_roots=(),
        test_roots=(),
    )

    assert cfg.project_root == tmp_path.resolve()
    assert cfg.package_roots == ((tmp_path / "src/py_init_tools").resolve(),)
    assert cfg.test_roots == ((tmp_path / "tests").resolve(),)
    assert cfg.generated_marker == "Generated by py-init-tools"
    assert cfg.package_version is None
    assert cfg.package_description == "Python package."
    assert cfg.generate_root_reexports is False
    assert cfg.reexport_allowlist == frozenset()
    assert cfg.flat_subdirs == frozenset()
    assert cfg.discovery_mode == "classes_functions"
    assert cfg.export_constants is False
    assert cfg.export_type_aliases is False
    assert "__pycache__" in cfg.ignored_dir_names
    assert ".pixi" in cfg.ignored_dir_names
    assert cfg.private_names_by_module == {}
    assert cfg.private_names_by_dir == {}


def test_load_config_reads_pyproject_configuration(tmp_path: Path) -> None:
    """Load configuration from [tool.py-init-tools]."""
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(
        """
[tool.py-init-tools]
package_roots = ["src/example_pkg"]
test_roots = ["tests/unit"]
generated_marker = "Generated by test"
package_version = "1.2.3"
package_description = "Example package."
generate_root_reexports = true
reexport_allowlist = ["example_pkg.api"]
flat_subdirs = ["example_pkg.plugins"]
discovery_mode = "all_public"
export_constants = true
export_type_aliases = true
ignored_dir_names = ["__pycache__", ".custom_cache"]

[tool.py-init-tools.private_names_by_module]
"example_pkg.module" = ["HiddenClass", "private_function"]

[tool.py-init-tools.private_names_by_dir]
"example_pkg/internal" = ["InternalThing"]
""",
        encoding="utf-8",
    )

    cfg = load_config(
        cwd=tmp_path,
        package_roots=(),
        test_roots=(),
    )

    assert cfg.package_roots == ((tmp_path / "src/example_pkg").resolve(),)
    assert cfg.test_roots == ((tmp_path / "tests/unit").resolve(),)
    assert cfg.generated_marker == "Generated by test"
    assert cfg.package_version == "1.2.3"
    assert cfg.package_description == "Example package."
    assert cfg.generate_root_reexports is True
    assert cfg.reexport_allowlist == frozenset({"example_pkg.api"})
    assert cfg.flat_subdirs == frozenset({"example_pkg.plugins"})
    assert cfg.discovery_mode == "all_public"
    assert cfg.export_constants is True
    assert cfg.export_type_aliases is True
    assert cfg.ignored_dir_names == frozenset({"__pycache__", ".custom_cache"})
    assert cfg.private_names_by_module == {
        "example_pkg.module": frozenset({"HiddenClass", "private_function"})
    }
    assert cfg.private_names_by_dir == {
        "example_pkg/internal": frozenset({"InternalThing"})
    }


def test_load_config_cli_roots_override_pyproject_roots(tmp_path: Path) -> None:
    """Prefer CLI package and test roots over configured roots."""
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(
        """
[tool.py-init-tools]
package_roots = ["src/from_config"]
test_roots = ["tests/from_config"]
""",
        encoding="utf-8",
    )

    cfg = load_config(
        cwd=tmp_path,
        package_roots=("src/from_cli",),
        test_roots=("tests/from_cli",),
    )

    assert cfg.package_roots == ((tmp_path / "src/from_cli").resolve(),)
    assert cfg.test_roots == ((tmp_path / "tests/from_cli").resolve(),)


def test_load_config_ignores_invalid_values(tmp_path: Path) -> None:
    """Fallback to defaults when pyproject values have invalid types."""
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(
        """
[tool.py-init-tools]
package_roots = "not-a-list"
test_roots = 123
generated_marker = false
package_version = ["invalid"]
package_description = 42
generate_root_reexports = "yes"
reexport_allowlist = "not-a-list"
flat_subdirs = 123
discovery_mode = "invalid"
export_constants = "yes"
export_type_aliases = "yes"
ignored_dir_names = "not-a-list"
private_names_by_module = []
private_names_by_dir = []
""",
        encoding="utf-8",
    )

    cfg = load_config(
        cwd=tmp_path,
        package_roots=(),
        test_roots=(),
    )

    assert cfg.package_roots == ((tmp_path / "src/py_init_tools").resolve(),)
    assert cfg.test_roots == ((tmp_path / "tests").resolve(),)
    assert cfg.generated_marker == "Generated by py-init-tools"
    assert cfg.package_version is None
    assert cfg.package_description == "Python package."
    assert cfg.generate_root_reexports is False
    assert cfg.reexport_allowlist == frozenset()
    assert cfg.flat_subdirs == frozenset()
    assert cfg.discovery_mode == "classes_functions"
    assert cfg.export_constants is False
    assert cfg.export_type_aliases is False
    assert "__pycache__" in cfg.ignored_dir_names
    assert cfg.private_names_by_module == {}
    assert cfg.private_names_by_dir == {}
