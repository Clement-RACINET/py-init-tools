"""Tests for the command-line interface."""

from __future__ import annotations

import sys
from typing import TYPE_CHECKING

import pytest

from py_init_tools import cli
from py_init_tools.cli import build_parser, main, parse_args
from py_init_tools.models import GeneratedFile, InitToolConfig

if TYPE_CHECKING:
    from pathlib import Path

ARGPARSE_USAGE_ERROR_EXIT_CODE = 2


def make_config(tmp_path: Path) -> InitToolConfig:
    """Create a minimal CLI test configuration."""
    return InitToolConfig(
        project_root=tmp_path,
        package_roots=(tmp_path / "src" / "example_pkg",),
        test_roots=(tmp_path / "tests",),
        discovery_mode="classes_functions",
        reexport_allowlist=frozenset({"subpkg"}),
        generated_marker="Generated by test",
    )


def make_generated_file(tmp_path: Path) -> GeneratedFile:
    """Create a generated file candidate."""
    return GeneratedFile(
        path=tmp_path / "src" / "example_pkg" / "__init__.py",
        content="# Generated by test\n",
    )


def test_parse_args_uses_expected_defaults() -> None:
    """Parse default CLI arguments."""
    parser = build_parser()
    args = parse_args(parser, [])

    assert args.package_root == []
    assert args.test_root == []
    assert args.write is False
    assert args.check is False
    assert args.overwrite_manual is False
    assert args.ignore_manual_in_check is False
    assert args.skip_tests is False


def test_parse_args_accepts_repeated_package_roots() -> None:
    """Parse repeated package root options."""
    parser = build_parser()
    args = parse_args(
        parser,
        [
            "--package-root",
            "src/pkg_a",
            "--package-root",
            "src/pkg_b",
        ],
    )

    assert args.package_root == ["src/pkg_a", "src/pkg_b"]


def test_parse_args_accepts_repeated_test_roots() -> None:
    """Parse repeated test root options."""
    parser = build_parser()
    args = parse_args(
        parser,
        [
            "--test-root",
            "tests/unit",
            "--test-root",
            "tests/integration",
        ],
    )

    assert args.test_root == ["tests/unit", "tests/integration"]


def test_parse_args_accepts_boolean_flags() -> None:
    """Parse boolean CLI flags."""
    parser = build_parser()
    args = parse_args(
        parser,
        [
            "--write",
            "--overwrite-manual",
            "--ignore-manual-in-check",
            "--skip-tests",
        ],
    )

    assert args.write is True
    assert args.check is False
    assert args.overwrite_manual is True
    assert args.ignore_manual_in_check is True
    assert args.skip_tests is True


def test_parse_args_accepts_check_flag() -> None:
    """Parse check mode."""
    parser = build_parser()
    args = parse_args(parser, ["--check"])

    assert args.write is False
    assert args.check is True


def test_main_rejects_write_and_check_together(
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Reject incompatible --write and --check options."""
    monkeypatch.setattr(sys, "argv", ["pyinit", "--write", "--check"])

    with pytest.raises(SystemExit) as exc_info:
        main()

    assert exc_info.value.code == ARGPARSE_USAGE_ERROR_EXIT_CODE

    captured = capsys.readouterr()

    assert "--write and --check cannot be used together." in captured.err


def test_main_runs_dry_run_by_default(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Run in dry-run mode when neither --write nor --check is passed."""
    cfg = make_config(tmp_path)
    generated_file = make_generated_file(tmp_path)

    def fake_load_config(
        *,
        cwd: Path,
        package_roots: tuple[str, ...],
        test_roots: tuple[str, ...],
    ) -> InitToolConfig:
        assert cwd == tmp_path
        assert package_roots == ()
        assert test_roots == ()
        return cfg

    def fake_generate_files(
        loaded_cfg: InitToolConfig,
        *,
        include_tests: bool,
    ) -> list[GeneratedFile]:
        assert loaded_cfg == cfg
        assert include_tests is True
        return [generated_file]

    def fake_apply_files(
        loaded_cfg: InitToolConfig,
        generated_files: list[GeneratedFile],
        *,
        dry_run: bool,
        overwrite_manual: bool,
    ) -> bool:
        assert loaded_cfg == cfg
        assert generated_files == [generated_file]
        assert dry_run is True
        assert overwrite_manual is False
        return True

    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(sys, "argv", ["pyinit"])
    monkeypatch.setattr(cli, "load_config", fake_load_config)
    monkeypatch.setattr(cli, "generate_files", fake_generate_files)
    monkeypatch.setattr(cli, "apply_files", fake_apply_files)

    main()

    captured = capsys.readouterr()

    assert "Generated files : 1" in captured.out
    assert "Discovery mode  : classes_functions" in captured.out
    assert "Dry-run mode. No files will be written." in captured.out
    assert "Done." in captured.out


