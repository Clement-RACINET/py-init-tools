def test_apply_files_returns_true_when_all_files_are_written(
    tmp_path: Path,
) -> None:
    """Return true when all generated files are successfully applied."""
    cfg = make_config(tmp_path)
    generated_files = [
        make_generated_file(tmp_path, "src/example_pkg/__init__.py"),
        make_generated_file(tmp_path, "src/example_pkg/subpkg/__init__.py"),
    ]

    result = apply_files(
        cfg,
        generated_files,
        dry_run=False,
        overwrite_manual=False,
    )

    assert result is True
    assert generated_files[0].path.exists()
    assert generated_files[1].path.exists()


def test_apply_files_returns_false_when_one_file_is_skipped(
    tmp_path: Path,
) -> None:
    """Return false when at least one file cannot be applied."""
    cfg = make_config(tmp_path)
    first_file = make_generated_file(tmp_path, "src/example_pkg/__init__.py")
    second_file = make_generated_file(tmp_path, "src/example_pkg/manual/__init__.py")
    write_text(second_file.path, "# Manual file\n")

    result = apply_files(
        cfg,
        [first_file, second_file],
        dry_run=False,
        overwrite_manual=False,
    )

    assert result is False
    assert first_file.path.exists()
    assert second_file.path.read_text(encoding="utf-8") == "# Manual file\n"


def test_check_files_returns_true_when_all_files_are_valid(tmp_path: Path) -> None:
    """Return true when all generated files are up to date."""
    cfg = make_config(tmp_path)
    generated_files = [
        make_generated_file(tmp_path, "src/example_pkg/__init__.py"),
        make_generated_file(tmp_path, "src/example_pkg/subpkg/__init__.py"),
    ]

    for generated_file in generated_files:
        write_text(generated_file.path, generated_file.content)

    result = check_files(
        cfg,
        generated_files,
        ignore_manual=False,
    )

    assert result is True


def test_check_files_returns_false_when_one_file_is_invalid(tmp_path: Path) -> None:
    """Return false when at least one generated file is invalid."""
    cfg = make_config(tmp_path)
    valid_file = make_generated_file(tmp_path, "src/example_pkg/__init__.py")
    missing_file = make_generated_file(tmp_path, "src/example_pkg/missing/__init__.py")

    write_text(valid_file.path, valid_file.content)

    result = check_files(
        cfg,
        [valid_file, missing_file],
        ignore_manual=False,
    )

    assert result is False
